    #[test]
    fn apportions_a_missing_reasoning_split_by_generated_byte_share() {
        let mut usage = Usage::from_openai(&json!({"usage": {
            "prompt_tokens": 60,
            "completion_tokens": 400,
            "total_tokens": 460
        }}));
        assert!(!usage.reasoning_reported);
        assert!(usage.estimate_reasoning(GeneratedTextBytes {
            reasoning: 3_500,
            other: 1_200
        }));
        // 400 * 3500 / 4700 rounds to 298 and stays inside the exact total.
        assert_eq!(usage.reasoning_estimated_tokens, 298);
        assert_eq!(usage.reasoning_tokens, 0);
        assert_eq!(usage.output_tokens, 400);
        // A second observation never overwrites the first estimate.
        assert!(!usage.estimate_reasoning(GeneratedTextBytes {
            reasoning: 10,
            other: 0
        }));
        assert_eq!(usage.reasoning_estimated_tokens, 298);
    }

