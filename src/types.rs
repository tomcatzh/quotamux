use serde::{Deserialize, Serialize};
use serde_json::{Value, json};

use crate::config::AdapterKind;

#[derive(Clone, Copy, Debug, Deserialize, Eq, Hash, PartialEq, Serialize)]
pub enum Protocol {
    #[serde(rename = "openai-chat", alias = "open-ai-chat")]
    OpenAiChat,
    #[serde(rename = "openai-responses", alias = "open-ai-responses")]
    OpenAiResponses,
    #[serde(rename = "anthropic-messages")]
    AnthropicMessages,
}

impl Protocol {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::OpenAiChat => "openai-chat",
            Self::OpenAiResponses => "openai-responses",
            Self::AnthropicMessages => "anthropic-messages",
        }
    }
}

#[derive(Clone, Copy, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum FailureClass {
    ClientRequest,
    ProviderAmbiguousRejection,
    ProviderAuth,
    ProviderBilling,
    ProviderConfiguration,
    ProviderCapacity,
    ProviderQuota,
    ProviderTransient,
    StreamFailure,
    ProviderUnknown4xx,
    ProviderUnknown5xxOrTransport,
    ClientCancelled,
    FallbackUnavailable,
    LocalCapacity,
}

impl FailureClass {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::ClientRequest => "client_request",
            Self::ProviderAmbiguousRejection => "provider_ambiguous_rejection",
            Self::ProviderAuth => "provider_auth",
            Self::ProviderBilling => "provider_billing",
            Self::ProviderConfiguration => "provider_configuration",
            Self::ProviderCapacity => "provider_capacity",
            Self::ProviderQuota => "provider_quota",
            Self::ProviderTransient => "provider_transient",
            Self::StreamFailure => "stream_failure",
            Self::ProviderUnknown4xx => "provider_unknown_4xx",
            Self::ProviderUnknown5xxOrTransport => "provider_unknown_5xx_or_transport",
            Self::ClientCancelled => "client_cancelled",
            Self::FallbackUnavailable => "fallback_unavailable",
            Self::LocalCapacity => "local_capacity",
        }
    }

    pub const fn allows_fallback(self) -> bool {
        !matches!(self, Self::ClientRequest | Self::ClientCancelled)
    }

    pub const fn retries_same_target_once(self) -> bool {
        matches!(self, Self::ProviderAmbiguousRejection)
    }

    pub const fn affects_circuit(self) -> bool {
        !matches!(
            self,
            Self::ClientRequest
                | Self::ClientCancelled
                | Self::ProviderAmbiguousRejection
                | Self::LocalCapacity
        )
    }
}

#[derive(Clone, Debug, Default, Deserialize, Serialize)]
pub struct Usage {
    pub input_tokens: u64,
    pub cache_hit_tokens: u64,
    pub cache_miss_tokens: u64,
    pub reasoning_tokens: u64,
    /// Whether the upstream reported a reasoning/thinking token count at all.
    /// Anthropic usage has no separate field, and some upstreams omit the detail.
    #[serde(default)]
    pub reasoning_reported: bool,
    /// Local estimate used only when the upstream omits the reasoning split.
    ///
    /// Ollama Cloud's OpenAI-compatible endpoint never returns
    /// `completion_tokens_details`, so those routes have no provider-reported
    /// reasoning count. When thinking text is observed anyway, the exact
    /// `output_tokens` total is apportioned by the share of generated bytes that
    /// were reasoning text. The result never exceeds `output_tokens`, never
    /// replaces a reported count, and stays internal to QuotaMux statistics.
    #[serde(default)]
    pub reasoning_estimated_tokens: u64,
    pub output_tokens: u64,
    pub total_tokens: u64,
    pub provider_reported: bool,
}

/// Bytes of generated text observed while reading one response.
///
/// Upstreams that omit `completion_tokens_details` still stream the thinking
/// text itself. Counting bytes lets QuotaMux apportion the exact output-token
/// total into reported and thinking shares without storing any prompt,
/// reasoning or answer content.
#[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]
pub struct GeneratedTextBytes {
    /// Thinking/reasoning text, including `reasoning` and `reasoning_content`.
    pub reasoning: u64,
    /// Answer text and generated tool-call arguments.
    pub other: u64,
}

impl GeneratedTextBytes {
    pub fn is_empty(&self) -> bool {
        self.reasoning == 0 && self.other == 0
    }

    fn observe_text(target: &mut u64, value: Option<&Value>) {
        if let Some(text) = value.and_then(Value::as_str) {
            *target = target.saturating_add(text.len() as u64);
        }
    }

    /// Counts one chat-completions message or streaming delta.
    fn observe_chat_message(&mut self, message: &Value) {
        Self::observe_text(&mut self.reasoning, message.get("reasoning_content"));
        Self::observe_text(&mut self.reasoning, message.get("reasoning"));
        Self::observe_text(&mut self.other, message.get("content"));
        for call in message
            .get("tool_calls")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
        {
            Self::observe_text(&mut self.other, call.pointer("/function/arguments"));
        }
        Self::observe_text(&mut self.other, message.pointer("/function_call/arguments"));
    }

    /// Counts one `chat.completion.chunk` or `chat.completion` body.
    pub fn observe_chat_chunk(&mut self, chunk: &Value) {
        for choice in chunk
            .get("choices")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
        {
            if let Some(message) = choice.get("message").filter(|value| value.is_object()) {
                self.observe_chat_message(message);
            }
            if let Some(delta) = choice.get("delta").filter(|value| value.is_object()) {
                self.observe_chat_message(delta);
            }
        }
    }

    fn observe_anthropic_content(&mut self, content: &Value) {
        for block in content.as_array().into_iter().flatten() {
            match block.get("type").and_then(Value::as_str) {
                Some("thinking") => Self::observe_text(&mut self.reasoning, block.get("thinking")),
                Some("text") => Self::observe_text(&mut self.other, block.get("text")),
                Some("tool_use") => {
                    let bytes = block
                        .get("input")
                        .map(|input| serde_json::to_vec(input).map_or(0, |encoded| encoded.len()))
                        .unwrap_or(0);
                    self.other = self.other.saturating_add(bytes as u64);
                }
                _ => {}
            }
        }
    }

    fn observe_responses_output(&mut self, output: &Value) {
        for item in output.as_array().into_iter().flatten() {
            match item.get("type").and_then(Value::as_str) {
                Some("reasoning") => {
                    for part in item
                        .get("content")
                        .and_then(Value::as_array)
                        .into_iter()
                        .flatten()
                    {
                        Self::observe_text(&mut self.reasoning, part.get("text"));
                    }
                    Self::observe_text(&mut self.reasoning, item.get("summary_text"));
                }
                Some("message") => {
                    for part in item
                        .get("content")
                        .and_then(Value::as_array)
                        .into_iter()
                        .flatten()
                    {
                        Self::observe_text(&mut self.other, part.get("text"));
                    }
                }
                Some("function_call") => {
                    Self::observe_text(&mut self.other, item.get("arguments"));
                }
                _ => {}
            }
        }
    }

    /// Counts generated text in a non-streaming upstream response body.
    pub fn observe_response(protocol: Protocol, value: &Value) -> Self {
        let mut bytes = Self::default();
        match protocol {
            Protocol::OpenAiChat => bytes.observe_chat_chunk(value),
            Protocol::OpenAiResponses => {
                bytes.observe_responses_output(value.get("output").unwrap_or(&Value::Null));
            }
            Protocol::AnthropicMessages => {
                bytes.observe_anthropic_content(value.get("content").unwrap_or(&Value::Null));
            }
        }
        bytes
    }

    /// Counts generated text in one raw upstream SSE event of `protocol`.
    ///
    /// Used on the native path, where the client protocol already equals the
    /// egress protocol and chunks are forwarded without translation.
    pub fn observe_stream_event(&mut self, protocol: Protocol, event: &Value) {
        match protocol {
            Protocol::OpenAiChat => self.observe_chat_chunk(event),
            Protocol::OpenAiResponses => {
                let delta = event.get("delta").unwrap_or(&Value::Null);
                match event.get("type").and_then(Value::as_str) {
                    Some(
                        "response.reasoning_text.delta" | "response.reasoning_summary_text.delta",
                    ) => {
                        Self::observe_text(&mut self.reasoning, Some(delta));
                    }
                    Some(
                        "response.output_text.delta"
                        | "response.function_call_arguments.delta"
                        | "response.refusal.delta",
                    ) => Self::observe_text(&mut self.other, Some(delta)),
                    _ => {}
                }
            }
            Protocol::AnthropicMessages => {
                let delta = event.get("delta").unwrap_or(&Value::Null);
                match delta.get("type").and_then(Value::as_str) {
                    Some("thinking_delta") => {
                        Self::observe_text(&mut self.reasoning, delta.get("thinking"));
                    }
                    Some("text_delta") => Self::observe_text(&mut self.other, delta.get("text")),
                    Some("input_json_delta") => {
                        Self::observe_text(&mut self.other, delta.get("partial_json"));
                    }
                    _ => {}
                }
            }
        }
    }
}

impl Usage {
    pub fn from_openai(value: &Value) -> Self {
        let Some(usage) = value.get("usage") else {
            return Self::default();
        };
        let prompt = usage
            .get("prompt_tokens")
            .and_then(Value::as_u64)
            .unwrap_or(0);
        let output = usage
            .get("completion_tokens")
            .and_then(Value::as_u64)
            .unwrap_or(0);
        let details = usage.get("prompt_tokens_details").unwrap_or(&Value::Null);
        let completion_details = usage
            .get("completion_tokens_details")
            .unwrap_or(&Value::Null);
        let cache_hit = usage
            .get("prompt_cache_hit_tokens")
            .and_then(Value::as_u64)
            .or_else(|| details.get("cached_tokens").and_then(Value::as_u64))
            .unwrap_or(0);
        let cache_miss = usage
            .get("prompt_cache_miss_tokens")
            .and_then(Value::as_u64)
            .unwrap_or_else(|| prompt.saturating_sub(cache_hit));
        let reasoning_detail = completion_details.get("reasoning_tokens");
        let reasoning = reasoning_detail.and_then(Value::as_u64).unwrap_or(0);
        Self {
            input_tokens: prompt,
            cache_hit_tokens: cache_hit,
            cache_miss_tokens: cache_miss,
            reasoning_tokens: reasoning,
            reasoning_reported: reasoning_detail.is_some(),
            reasoning_estimated_tokens: 0,
            output_tokens: output,
            total_tokens: usage
                .get("total_tokens")
                .and_then(Value::as_u64)
                .unwrap_or_else(|| prompt.saturating_add(output)),
            provider_reported: true,
        }
    }

    pub fn as_json(&self) -> Value {
        json!({
            "input_tokens": self.input_tokens,
            "cache_hit_tokens": self.cache_hit_tokens,
            "cache_miss_tokens": self.cache_miss_tokens,
            "reasoning_tokens": self.reasoning_tokens,
            "reasoning_reported": self.reasoning_reported,
            "reasoning_estimated_tokens": self.reasoning_estimated_tokens,
            "output_tokens": self.output_tokens,
            "total_tokens": self.total_tokens,
            "provider_reported": self.provider_reported,
        })
    }

    /// Apportions the exact output-token total when the upstream omitted the
    /// reasoning split but thinking text was observed.
    ///
    /// The reasoning share is `output_tokens * reasoning_bytes / total_bytes`,
    /// rounded to nearest and capped at `output_tokens`. A provider-reported
    /// count always wins, and a missing total or missing thinking text leaves
    /// the estimate at zero. Returns whether an estimate was recorded.
    pub fn estimate_reasoning(&mut self, bytes: GeneratedTextBytes) -> bool {
        if self.reasoning_reported
            || self.reasoning_estimated_tokens > 0
            || bytes.reasoning == 0
            || self.output_tokens == 0
        {
            return false;
        }
        let total_bytes = bytes.reasoning.saturating_add(bytes.other);
        if total_bytes == 0 {
            return false;
        }
        let scaled = u128::from(self.output_tokens) * u128::from(bytes.reasoning);
        let rounded = (scaled + u128::from(total_bytes) / 2) / u128::from(total_bytes);
        let estimate = u64::try_from(rounded)
            .unwrap_or(u64::MAX)
            .min(self.output_tokens);
        if estimate == 0 {
            return false;
        }
        self.reasoning_estimated_tokens = estimate;
        true
    }

    pub fn from_responses(value: &Value) -> Self {
        let Some(usage) = value.get("usage") else {
            return Self::default();
        };
        let input = usage
            .get("input_tokens")
            .and_then(Value::as_u64)
            .unwrap_or(0);
        let output = usage
            .get("output_tokens")
            .and_then(Value::as_u64)
            .unwrap_or(0);
        let cache_hit = usage
            .pointer("/input_tokens_details/cached_tokens")
            .and_then(Value::as_u64)
            .unwrap_or(0);
        let reasoning_detail = usage.pointer("/output_tokens_details/reasoning_tokens");
        let reasoning = reasoning_detail.and_then(Value::as_u64).unwrap_or(0);
        Self {
            input_tokens: input,
            cache_hit_tokens: cache_hit,
            cache_miss_tokens: input.saturating_sub(cache_hit),
            reasoning_tokens: reasoning,
            reasoning_reported: reasoning_detail.is_some(),
            reasoning_estimated_tokens: 0,
            output_tokens: output,
            total_tokens: usage
                .get("total_tokens")
                .and_then(Value::as_u64)
                .unwrap_or_else(|| input.saturating_add(output)),
            provider_reported: true,
        }
    }

    pub fn from_anthropic(value: &Value) -> Self {
        let Some(usage) = value.get("usage") else {
            return Self::default();
        };
        let uncached_input = usage
            .get("input_tokens")
            .and_then(Value::as_u64)
            .unwrap_or(0);
        let cache_creation = usage
            .get("cache_creation_input_tokens")
            .and_then(Value::as_u64)
            .unwrap_or(0);
        let output = usage
            .get("output_tokens")
            .and_then(Value::as_u64)
            .unwrap_or(0);
        let cache_hit = usage
            .get("cache_read_input_tokens")
            .and_then(Value::as_u64)
            .unwrap_or(0);
        let cache_miss = uncached_input.saturating_add(cache_creation);
        let input = cache_miss.saturating_add(cache_hit);
        let reasoning = usage
            .pointer("/output_tokens_details/thinking_tokens")
            .and_then(Value::as_u64);
        Self {
            input_tokens: input,
            cache_hit_tokens: cache_hit,
            cache_miss_tokens: cache_miss,
            reasoning_tokens: reasoning.unwrap_or(0),
            reasoning_reported: reasoning.is_some(),
            reasoning_estimated_tokens: 0,
            output_tokens: output,
            total_tokens: input.saturating_add(output),
            provider_reported: true,
        }
    }

    pub fn observe_anthropic_stream_event(&mut self, event: &Value) {
        let event_type = event.get("type").and_then(Value::as_str);
        let usage = if event_type == Some("message_start") {
            event.pointer("/message/usage")
        } else {
            event.get("usage")
        };
        let Some(usage) = usage.filter(|usage| !usage.is_null()) else {
            return;
        };

        if usage.get("input_tokens").is_some()
            || usage.get("cache_creation_input_tokens").is_some()
            || usage.get("cache_read_input_tokens").is_some()
        {
            let observed = Self::from_anthropic(&json!({"usage":usage}));
            self.input_tokens = observed.input_tokens;
            self.cache_hit_tokens = observed.cache_hit_tokens;
            self.cache_miss_tokens = observed.cache_miss_tokens;
        }
        if let Some(output) = usage.get("output_tokens").and_then(Value::as_u64) {
            self.output_tokens = output;
        }

        if let Some(reasoning) = usage
            .pointer("/output_tokens_details/thinking_tokens")
            .and_then(Value::as_u64)
        {
            self.reasoning_tokens = reasoning;
            self.reasoning_reported = true;
            self.reasoning_estimated_tokens = 0;
        }
        self.total_tokens = self.input_tokens.saturating_add(self.output_tokens);
        self.provider_reported = true;
    }
}

